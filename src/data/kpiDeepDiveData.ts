export function getKpiDeepDive(role: UserRole, kpiId: string): {
  kpiItem: RoleKpiItem;
  deepDive: KpiDeepDiveRecord;
} {
  const roleConfig =
    ROLE_DASHBOARDS_CONFIG[role] || ROLE_DASHBOARDS_CONFIG['Performance Director'];
  const kpiItem =
    roleConfig.kpis.find((k) => k.id === kpiId) || roleConfig.kpis[0];
  const deepDive =
    KPI_DEEP_DIVE_MAP[kpiItem.id] ||
    KPI_DEEP_DIVE_MAP['squad-availability'];
  return { kpiItem, deepDive };
}


